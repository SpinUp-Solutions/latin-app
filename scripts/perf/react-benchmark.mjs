const percentile = (values, p) => {
  if (!values.length) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.ceil((p / 100) * sorted.length) - 1)];
};
const median = values => percentile(values, 50);

async function runOnce(browser, base, scenarioName, mode) {
  const scenario = scenarios[scenarioName];
  // Student progress is persisted, so every player run starts from a freshly seeded emulator.
  if (scenario.reseed)
    execFileSync(process.execPath, [new URL('./seed-benchmark-lesson.mts', import.meta.url).pathname], {
      stdio: 'ignore',
    });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(String(error).slice(0, 300)));
  await signIn(page, base, ...scenario.user);
  if (mode === 'profile') await page.addInitScript(installReactHook);
  await page.addInitScript(installInteractionObserver);
  const cdp = await context.newCDPSession(page);
  await cdp.send('Performance.enable');
  await cdp.send('Network.enable');
  let scriptBytes = 0;
  cdp.on('Network.loadingFinished', event => {
    if (scriptRequests.has(event.requestId)) scriptBytes += event.encodedDataLength;
  });
  const scriptRequests = new Set();
  cdp.on('Network.responseReceived', event => {
    if (event.type === 'Script') scriptRequests.add(event.requestId);
  });

  await cdp.send('Emulation.setCPUThrottlingRate', { rate: CPU_THROTTLE });
  const loadStart = Date.now();
  await page.goto(base + scenario.path);
  await scenario.ready(page);
  const loadMs = Date.now() - loadStart;
  await page.waitForTimeout(1500);

  const metrics = async () =>
    Object.fromEntries((await cdp.send('Performance.getMetrics')).metrics.map(m => [m.name, m.value]));
  const before = await metrics();
  await page.evaluate(() => {
    window.__perfEvents.length = 0;
    window.__perfLoAF.length = 0;
    window.__perfReactReset?.();
  });
  const started = Date.now();
  const interactions = await scenario.run(page);
  const wallMs = Date.now() - started;
  const after = await metrics();
  const collected = await page.evaluate(() => ({
    events: window.__perfEvents,
    loaf: window.__perfLoAF,
    react: window.__perfReact ?? null,
  }));
  await cdp.send('Emulation.setCPUThrottlingRate', { rate: 1 });
  await context.close();

  const byInteraction = new Map();
  for (const event of collected.events)
    byInteraction.set(event.id, Math.max(byInteraction.get(event.id) ?? 0, event.duration));
  const slow = [...byInteraction.values()];
  // Interactions faster than the 16ms observer threshold are not reported; count them as 16ms.
  const latencies = slow.concat(Array(Math.max(0, interactions - slow.length)).fill(16));
  return {
    loadMs,
    scriptBytes,
    wallMs,
    interactions,
    scriptMs: (after.ScriptDuration - before.ScriptDuration) * 1000,
    taskMs: (after.TaskDuration - before.TaskDuration) * 1000,
    layoutMs: (after.LayoutDuration - before.LayoutDuration) * 1000,
    p50: percentile(latencies, 50),
    p75: percentile(latencies, 75),
    p98: percentile(latencies, 98),
    maxLatency: Math.max(...latencies),
    over100: latencies.filter(v => v > 100).length,
    over200: latencies.filter(v => v > 200).length,
    loafBlockingMs: collected.loaf.reduce((sum, entry) => sum + entry.blocking, 0),
    react: collected.react
      ? {
          commits: collected.react.commits,
          renders: collected.react.renders,
          renderMs: collected.react.renderMs,
          top: Object.entries(collected.react.byName)
            .sort((a, b) => b[1] - a[1])
            .slice(0, 15),
        }
      : null,
    errors,
  };
}

const browser = await chromium.launch({
  args: ['--disable-renderer-backgrounding', '--disable-background-timer-throttling'],
});
const results = {};
const variantNames = Object.keys(VARIANTS);
for (const scenarioName of SCENARIOS) {
  results[scenarioName] = {};
  for (const mode of ['timing', 'profile']) {
    const runs = mode === 'timing' ? RUNS : PROFILE_RUNS;
    for (let i = 0; i < runs; i += 1) {
      // Alternate order each iteration so thermal/cache drift affects both variants equally.
      const order = i % 2 === 0 ? variantNames : [...variantNames].reverse();
      for (const variant of order) {
        const result = await runOnce(browser, VARIANTS[variant][mode], scenarioName, mode);
        ((results[scenarioName][variant] ??= {})[mode] ??= []).push(result);
        console.log(
          `${scenarioName} ${mode} #${i + 1} ${variant}: p98=${result.p98.toFixed(0)}ms max=${result.maxLatency.toFixed(0)}ms script=${result.scriptMs.toFixed(0)}ms task=${result.taskMs.toFixed(0)}ms` +
            (result.react
              ? ` commits=${result.react.commits} renders=${result.react.renders} reactMs=${result.react.renderMs.toFixed(0)}`
              : '') +
            (result.errors.length ? ` ERRORS=${result.errors.length}` : '')
        );
      }
    }
  }
}
await browser.close();
writeFileSync(OUT, JSON.stringify(results, null, 1));

const summarize = runs => {
  const keys = [
    'loadMs',
    'scriptBytes',
    'scriptMs',
    'taskMs',
    'layoutMs',
    'p50',
    'p75',
    'p98',
    'maxLatency',
    'over100',
    'over200',
    'loafBlockingMs',
  ];
  const out = Object.fromEntries(keys.map(key => [key, median(runs.map(run => run[key]))]));
  return out;
};
for (const scenarioName of SCENARIOS) {
  console.log(
    `\n=== ${scenarioName} (median of ${RUNS} timing runs, ${PROFILE_RUNS} profile runs, CPU ${CPU_THROTTLE}x) ===`
  );
  const rows = {};
  for (const variant of variantNames) {
    const data = results[scenarioName][variant];
    rows[variant] = summarize(data.timing);
    const profile = data.profile.map(run => run.react);
    rows[variant].reactCommits = median(profile.map(r => r.commits));
    rows[variant].reactRenders = median(profile.map(r => r.renders));
    rows[variant].reactRenderMs = median(profile.map(r => r.renderMs));
  }
  console.table(rows);
}
console.log(`\nRaw results: ${OUT}`);
