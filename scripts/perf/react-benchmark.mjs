// A/B benchmark of React rendering work and input latency between two production builds.
//
// Both builds run against the local Firebase emulators, never a deployed project:
//   1. node tests/e2e/start-emulators.mjs                 (with the env from playwright.config.ts)
//   2. node scripts/perf/seed-benchmark-lesson.mts
//   3. For each commit to compare, run `next build` and `next build --profile` in separate checkouts
//      and `next start -p <port>` each one with the same emulator env.
//   4. BASELINE_URL=... CANDIDATE_URL=... BASELINE_PROFILE_URL=... CANDIDATE_PROFILE_URL=... \
//      node scripts/perf/react-benchmark.mjs
//
// Timing (Event Timing interaction latency, Chrome main-thread time) comes from the standard builds.
// React commits, component renders, and render time come from the --profile builds through a
// minimal React DevTools hook. Runs alternate between the two builds under CPU throttling.
import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const RUNS = Number(process.env.RUNS ?? 7);
const PROFILE_RUNS = Number(process.env.PROFILE_RUNS ?? 3);
const CPU_THROTTLE = Number(process.env.CPU_THROTTLE ?? 4);
const SCENARIOS = (process.env.SCENARIOS ?? 'editor,player').split(',');
const VARIANTS = {
  baseline: { timing: process.env.BASELINE_URL, profile: process.env.BASELINE_PROFILE_URL },
  candidate: { timing: process.env.CANDIDATE_URL, profile: process.env.CANDIDATE_PROFILE_URL },
};
if (Object.values(VARIANTS).some(variant => !variant.timing || !variant.profile)) {
  throw new Error('Set BASELINE_URL, CANDIDATE_URL, BASELINE_PROFILE_URL, and CANDIDATE_PROFILE_URL.');
}
const OUT = process.env.OUT ?? join(tmpdir(), 'react-benchmark-results.json');

