// Installed before any page script: a minimal React DevTools hook that counts committed work.
function installReactHook() {
  const COMPONENT_TAGS = new Set([0, 1, 11, 14, 15]); // function, class, forwardRef, memo, simpleMemo
  const stats = { commits: 0, renders: 0, renderMs: 0, byName: {} };
  let previousCommit = 0;
  let nextId = 1;
  const nameOf = fiber => {
    const type = fiber.type;
    if (!type) return '?';
    return (
      type.displayName ||
      type.name ||
      type.render?.displayName ||
      type.render?.name ||
      type.type?.displayName ||
      type.type?.name ||
      'Anonymous'
    );
  };
  window.__perfReact = stats;
  window.__perfReactReset = () => {
    stats.commits = 0;
    stats.renders = 0;
    stats.renderMs = 0;
    stats.byName = {};
  };
  window.__REACT_DEVTOOLS_GLOBAL_HOOK__ = {
    supportsFiber: true,
    isDisabled: false,
    renderers: new Map(),
    inject(renderer) {
      const id = nextId++;
      this.renderers.set(id, renderer);
      return id;
    },
    checkDCE() {},
    onScheduleFiberRoot() {},
    onCommitFiberUnmount() {},
    onPostCommitFiberRoot() {},
    onCommitFiberRoot(_id, root) {
      const committedAt = performance.now();
      const host = root.current;
      stats.commits += 1;
      if (typeof host.actualDuration === 'number') stats.renderMs += host.actualDuration;
      const stack = [host];
      while (stack.length) {
        const fiber = stack.pop();
        // PerformedWork (flag 1) is only set when the component function actually ran in this render;
        // actualStartTime (profiling builds) tells us the fiber was visited in this render at all.
        if (COMPONENT_TAGS.has(fiber.tag) && (fiber.flags & 1) === 1 && fiber.actualStartTime >= previousCommit) {
          stats.renders += 1;
          const name = nameOf(fiber);
          stats.byName[name] = (stats.byName[name] ?? 0) + 1;
        }
        if (fiber.sibling) stack.push(fiber.sibling);
        if (fiber.child) stack.push(fiber.child);
      }
      previousCommit = committedAt;
    },
  };
}

function installInteractionObserver() {
  window.__perfEvents = [];
  new PerformanceObserver(list => {
    for (const entry of list.getEntries()) {
      if (entry.interactionId)
        window.__perfEvents.push({
          id: entry.interactionId,
          name: entry.name,
          duration: entry.duration,
          start: entry.startTime,
        });
    }
  }).observe({ type: 'event', durationThreshold: 16, buffered: true });
  window.__perfLoAF = [];
  new PerformanceObserver(list => {
    for (const entry of list.getEntries())
      window.__perfLoAF.push({ start: entry.startTime, duration: entry.duration, blocking: entry.blockingDuration });
  }).observe({ type: 'long-animation-frame', buffered: true });
}

async function signIn(page, base, email, landing) {
  await page.goto(base + '/login');
  await page.getByPlaceholder('name@example.com').fill(email);
  await page.getByPlaceholder('••••••••').fill('Playwright-pass-123!');
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.waitForURL(`**${landing}**`, { timeout: 30000 });
}

